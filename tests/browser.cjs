    await page.getByText("plan 10 · realizat 8 · abatere -2",{exact:false}).first().waitFor();
    await page.getByText("Salvat",{exact:true}).waitFor();
    await context.setOffline(true);
    await page.reload();
    await page.getByRole("heading",{name:"Plan versus realizat"}).waitFor();
    await page.getByLabel("Zonă / linie").fill("DEMO A");
    await page.getByText("plan 10 · realizat 8 · abatere -2",{exact:false}).first().waitFor();
    await page.goto(new URL("?mod=instruire", base).href);
